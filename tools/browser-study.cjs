const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:375,height:812}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto((process.env.STUDY_TEST_URL || 'http://127.0.0.1:8768/') + '?version=v2');
await page.locator('[data-work-version="v2"]').first().waitFor();
await page.waitForFunction(()=>document.querySelector('[data-work-version="v2"]').hasAttribute('aria-current'));
console.log('start',await page.locator('[data-study-time]').first().inputValue());
console.log('overflow start',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await page.locator('[data-open-study]').first().click();
await page.locator('#study-output table').waitFor({timeout:120000});
assert.equal(await page.locator('#study-output tbody tr').count(),6); console.log('comparison: six scenarios');
console.log('overflow study',await page.evaluate(()=>document.querySelector('#panel-study .scroll').scrollWidth>document.querySelector('#panel-study .scroll').clientWidth));
await page.screenshot({path:'results/v2-mobile-comparison.png',fullPage:true});
await page.locator('#panel-study [data-close]').click();
await page.locator('[data-study-time]').first().selectOption('4');
await page.locator('#btn-3d').click();
await page.locator('#bar').waitFor({state:'visible',timeout:30000});
console.log('live',await page.locator('#study-live-time').innerText());
await page.locator('#bar [data-open-study]').click();
await page.locator('#study-output table').waitFor({timeout:120000});
const time=await page.locator('#hud-time').innerText();
await page.waitForTimeout(1500);
assert.equal(time,await page.locator('#hud-time').innerText()); console.log('paused: true');
await page.locator('#panel-study [data-close]').click();
await page.locator('#btn-sound').click();
await page.locator('#sound-pop [data-work-version="v1"]').click();
await page.waitForFunction(()=>document.querySelector('[data-work-version="v1"]').hasAttribute('aria-current'));
assert.equal(await page.locator('[data-open-study]').first().isVisible(),false); console.log('v1 hides study: true');
console.log('v1 default',await page.evaluate(()=>JSON.parse(localStorage.getItem('slesar-ar-config-v1')||'null')));
await page.locator('#btn-3d').click();
await page.locator('#bar').waitFor({state:'visible'});
await page.locator('#btn-data').click();
assert.equal(await page.locator('#machines-table tbody tr').nth(1).locator('[data-f=mtbf]').inputValue(),'6');
await page.locator('#panel-data [data-close]').click();
await page.locator('#btn-sound').click();
await page.locator('#sound-pop [data-work-version=v2]').click();
await page.waitForFunction(()=>document.querySelector('[data-work-version=v2]').hasAttribute('aria-current'));
assert.equal(await page.locator('[data-study-time]').first().inputValue(),'4');
for(const size of [{width:320,height:568},{width:812,height:375},{width:1440,height:900}]) {
 await page.setViewportSize(size);
 await page.evaluate(()=>scrollTo(0,0));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert(await page.locator('.work-versions').first().evaluate(el=>el.getBoundingClientRect().top)>=0);
}
console.log('v1=6h, v2=4h: settings isolated; layouts 320px, landscape and desktop: pass');
console.log('pageerrors',errors);await browser.close();
if(errors.length)process.exit(1);
})();
